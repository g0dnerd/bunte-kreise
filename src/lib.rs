#[derive(Serialize, Deserialize)]
struct CoordSpace {
    coordinates: Vec<(f64, f64)>,
    min_x: f64,
    max_x: f64,
    min_y: f64,
    max_y: f64,
}

#[wasm_bindgen]
pub fn get_coordinates(coord_space: &JsValue) -> Result<JsValue, JsValue> {
    let coord_space: CoordSpace = serde_wasm_bindgen::from_value(coord_space.clone())?;
    Ok(serde_wasm_bindgen::to_value(&coord_space.coordinates)?)
}

#[wasm_bindgen]
pub fn get_labels(coord_space: &JsValue) -> Result<JsValue, JsValue> {
    let coord_space: CoordSpace = serde_wasm_bindgen::from_value(coord_space.clone())?;
    let mut labels: Vec<(usize, String)> = Vec::with_capacity(coord_space.coordinates.len());
    for (i, _) in coord_space.coordinates.iter().enumerate() {
        labels.push((i, idx_to_name(i)));
    }
    Ok(serde_wasm_bindgen::to_value(&labels)?)
}

#[wasm_bindgen]
pub fn load_coords(alg: &str) -> Result<JsValue, JsValue> {
    let coordinates: Vec<(f64, f64)> = match alg {
        "umap" => UMAP.into(),
        "tsne" => TSNE.into(),
        "mds" => MDS.into(),
        _ => return Err(JsValue::from_str("Invalid algorithm")),
    };

    let mut min_x = f64::INFINITY;
    let mut max_x = f64::NEG_INFINITY;
    let mut min_y = f64::INFINITY;
    let mut max_y = f64::NEG_INFINITY;
    for (x, y) in coordinates.iter() {
        min_x = min_x.min(*x);
        max_x = max_x.max(*x);
        min_y = min_y.min(*y);
        max_y = max_y.max(*y);
    }

    let coord_space = CoordSpace {
        coordinates,
        min_x,
        max_x,
        min_y,
        max_y,
    };

    Ok(serde_wasm_bindgen::to_value(&coord_space)?)
}
